create extension if not exists btree_gist;

create table stay (
	id bigint generated by default as identity primary key,
	room_id bigint not null references room (id),
	guest_id bigint not null references guest (id),
	check_in_date date not null,
	check_out_date date not null,
	guest_count integer not null check (guest_count between 1 and 20),
	created_at timestamptz not null,
	updated_at timestamptz not null,
	constraint stay_period_check check (check_out_date > check_in_date and check_out_date - check_in_date <= 30),
	constraint stay_room_id_period_excl exclude using gist (room_id with =, daterange(check_in_date, check_out_date, '[)') with &&)
);

create index stay_guest_id_check_in_date_id_idx on stay (guest_id, check_in_date desc, id desc);
