alter table room add column status varchar(20) not null default 'VACANT' check (status in ('VACANT', 'RESERVED', 'OCCUPIED', 'MAINTENANCE'));
alter table room alter column status drop default;

create table room_status_history (
	id bigint generated by default as identity primary key,
	room_id bigint not null references room (id),
	from_status varchar(20) check (from_status is null or from_status in ('VACANT', 'RESERVED', 'OCCUPIED', 'MAINTENANCE')),
	to_status varchar(20) not null check (to_status in ('VACANT', 'RESERVED', 'OCCUPIED', 'MAINTENANCE')),
	changed_by_id bigint not null references hotel_admin (id),
	changed_by_name varchar(50) not null check (changed_by_name <> '' and changed_by_name = btrim(changed_by_name)),
	created_at timestamptz not null,
	updated_at timestamptz not null
);

create index room_status_history_room_id_created_at_id_idx on room_status_history (room_id, created_at desc, id desc);
