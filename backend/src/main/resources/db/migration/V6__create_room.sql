create collation natural_sort (provider = icu, locale = 'und-u-kn');

create table room (
	id bigint generated by default as identity primary key,
	hotel_id bigint not null references hotel (id),
	name varchar(50) collate natural_sort not null check (name <> '' and name = btrim(name)),
	type varchar(50) not null check (type <> '' and type = btrim(type)),
	capacity integer not null check (capacity between 1 and 20),
	floor integer check (floor is null or floor between -10 and 200),
	description varchar(1000) check (description is null or (description <> '' and description = btrim(description))),
	check_in_time time not null check (extract(second from check_in_time) = 0),
	check_out_time time not null check (extract(second from check_out_time) = 0),
	version bigint not null,
	created_at timestamptz not null,
	updated_at timestamptz not null,
	constraint room_hotel_id_name_key unique (hotel_id, name)
);
