create table hotel (
	id bigint generated by default as identity primary key,
	name varchar(100) not null check (name <> '' and name = btrim(name)),
	address varchar(200) not null check (address <> '' and address = btrim(address)),
	phone varchar(20) not null check (phone ~ '^[0-9-]+$' and length(regexp_replace(phone, '[^0-9]', '', 'g')) between 8 and 11),
	description varchar(1000) check (description is null or (description <> '' and description = btrim(description))),
	version bigint not null,
	created_at timestamptz not null,
	updated_at timestamptz not null,
	constraint hotel_name_address_key unique (name, address)
);
