create table hotel_admin (
	id bigint generated by default as identity primary key,
	hotel_id bigint not null references hotel (id),
	login_id varchar(254) not null check (login_id <> '' and login_id = lower(btrim(login_id))),
	password_hash varchar(255) not null,
	name varchar(50) not null check (name <> '' and name = btrim(name)),
	role varchar(20) not null check (role in ('MASTER', 'OPERATOR')),
	active boolean not null,
	credential_version bigint not null,
	created_at timestamptz not null,
	updated_at timestamptz not null,
	constraint hotel_admin_login_id_key unique (login_id)
);

create unique index hotel_admin_master_key on hotel_admin (hotel_id) where role = 'MASTER';
