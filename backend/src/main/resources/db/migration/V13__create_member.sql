create table member (
	id bigint generated by default as identity primary key,
	email varchar(254) not null check (email <> '' and email = lower(btrim(email))),
	password_hash varchar(255) not null,
	name varchar(50) not null check (name <> '' and name = btrim(name)),
	phone varchar(20) not null check (phone ~ '^[0-9-]+$' and length(regexp_replace(phone, '[^0-9]', '', 'g')) between 8 and 11),
	created_at timestamptz not null,
	updated_at timestamptz not null,
	constraint member_email_key unique (email)
);
