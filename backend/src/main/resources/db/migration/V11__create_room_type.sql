create table room_type (
	id bigint generated by default as identity primary key,
	hotel_id bigint not null references hotel (id),
	name varchar(50) collate natural_sort not null check (name <> '' and name = btrim(name)),
	capacity integer not null check (capacity between 1 and 20),
	room_rate integer not null check (room_rate between 0 and 10000000),
	check_in_time time not null check (extract(second from check_in_time) = 0),
	check_out_time time not null check (extract(second from check_out_time) = 0),
	version bigint not null,
	created_at timestamptz not null,
	updated_at timestamptz not null,
	constraint room_type_hotel_id_name_key unique (hotel_id, name),
	constraint room_type_id_hotel_id_key unique (id, hotel_id)
);

-- 기존 객실은 호텔마다 type 글자값별로 유형을 만든다: 최대 인원은 그 유형 객실의 최댓값, 체크인·체크아웃 시각은 id가 가장 작은 객실의 값, 1박 요금은 100000원.
insert into room_type (hotel_id, name, capacity, room_rate, check_in_time, check_out_time, version, created_at, updated_at)
select distinct on (hotel_id, type)
	hotel_id, type, max(capacity) over (partition by hotel_id, type), 100000, check_in_time, check_out_time, 0, now(), now()
from room
order by hotel_id, type, id;

alter table room add column room_type_id bigint;
update room r set room_type_id = t.id from room_type t where t.hotel_id = r.hotel_id and t.name = (r.type collate natural_sort);
alter table room
	alter column room_type_id set not null,
	add constraint room_room_type_id_hotel_id_fkey foreign key (room_type_id, hotel_id) references room_type (id, hotel_id),
	drop column type,
	drop column capacity,
	drop column check_in_time,
	drop column check_out_time;

create index room_room_type_id_idx on room (room_type_id);
